export function icon(name) {
  const inner = ICONS[name] || ICONS.info;
  return `<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

export const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

export function parseDate(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d);
}

export function formatDate(d) {
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
}

export function timeAgo(iso) {
  const now = new Date();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const diff = Math.round((today - parseDate(iso)) / 86400000);
  if (diff <= 0) return 'Today';
  if (diff === 1) return 'Yesterday';
  if (diff < 7) return `${diff} days ago`;
  if (diff < 30) {
    const w = Math.floor(diff / 7);
    return w === 1 ? '1 week ago' : `${w} weeks ago`;
  }
  return formatDate(parseDate(iso));
}

export function toast(message, type = 'success') {
  const container = document.getElementById('toastContainer');
  if (!container) return;
  const iconName = type === 'error' ? 'alert' : type === 'info' ? 'info' : 'check';
  const el = document.createElement('div');
  el.className = `toast toast--${type}`;
  el.setAttribute('role', 'status');
  el.innerHTML = `${icon(iconName)}<span>${esc(message)}</span>`;
  container.appendChild(el);
  requestAnimationFrame(() => requestAnimationFrame(() => el.classList.add('show')));
  setTimeout(() => {
    el.classList.remove('show');
    setTimeout(() => el.remove(), 320);
  }, 3200);
  while (container.children.length > 4) container.firstElementChild.remove();
}

export function nav(path, params = {}) {
  const usp = new URLSearchParams();
  Object.entries(params).forEach(([k, v]) => {
    if (v !== undefined && v !== null && v !== '') usp.set(k, v);
  });
  const q = usp.toString();
  const target = '#' + path + (q ? '?' + q : '');
  if (location.hash === target) {
    try {
      window.dispatchEvent(new HashChangeEvent('hashchange'));
    } catch {
      window.dispatchEvent(new Event('hashchange'));
    }
  } else {
    location.hash = target;
  }
}

export function confirmModal({
  title,
  message,
  confirmLabel = 'Confirm',
  cancelLabel = 'Cancel',
  onConfirm,
  onCancel,
}) {
  const backdrop = document.createElement('div');
  backdrop.className = 'modal-backdrop';
  backdrop.innerHTML = `
    <div class="modal-card" role="dialog" aria-modal="true" aria-labelledby="modalTitleText">
      <div class="modal-icon" aria-hidden="true">${icon('check')}</div>
      <h3 id="modalTitleText">${esc(title)}</h3>
      <p>${esc(message)}</p>
      <div class="modal-actions">
        <button type="button" class="btn btn-secondary" data-modal-cancel>${esc(cancelLabel)}</button>
        <button type="button" class="btn btn-success" data-modal-confirm>${esc(confirmLabel)}</button>
      </div>
    </div>`;
  document.body.appendChild(backdrop);

  requestAnimationFrame(() => backdrop.classList.add('show'));

  let decided = false;

  function finish(callback) {
    if (decided) return;
    decided = true;
    document.removeEventListener('keydown', onKey);
    backdrop.classList.remove('show');
    setTimeout(() => backdrop.remove(), 200);
    if (typeof callback === 'function') callback();
  }
  function onKey(e) {
    if (e.key === 'Escape') finish(onCancel);
  }

  document.addEventListener('keydown', onKey);
  backdrop.addEventListener('click', (e) => {
    if (e.target === backdrop || e.target.closest('[data-modal-cancel]')) finish(onCancel);
  });
  const yesBtn = backdrop.querySelector('[data-modal-confirm]');
  yesBtn.addEventListener('click', () => finish(onConfirm));
  setTimeout(() => yesBtn.focus(), 60);
}

let revealObserver = null;

export function initReveals(root = document) {
  if (!revealObserver) {
    revealObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((e) => {
          if (e.isIntersecting) {
            e.target.classList.add('in-view');
            revealObserver.unobserve(e.target);
          }
        });
      },
      { threshold: 0.12 }
    );
  }
  $$('.reveal', root).forEach((el) => revealObserver.observe(el));
}
